import json, re, subprocess, os
from concurrent.futures import ThreadPoolExecutor
AUTO = re.compile(r"Written by (Codex|Claude)|Generated by \[?(Claude|Codex)|<!--|Generated with \[Claude", re.I)
BOTS = ("[bot]",)
ME = "olgabot"
d = json.load(open("data/2026-W43_prs.json"))
env = dict(os.environ, GH_PAGER="cat")
def gh(path):
    out = subprocess.run(["gh", "api", path, "--paginate"], capture_output=True, text=True, env=env)
    if out.returncode: raise SystemExit(out.stderr)
    txt = out.stdout.replace("][", ",")
    return json.loads(txt) if txt.strip() else []
def one(repo, n):
    ev = []
    for path, tkey in ((f"repos/{repo}/issues/{n}/comments?per_page=100", "created_at"),
                       (f"repos/{repo}/pulls/{n}/comments?per_page=100", "created_at"),
                       (f"repos/{repo}/pulls/{n}/reviews?per_page=100", "submitted_at")):
        for c in gh(path):
            login = (c.get("user") or {}).get("login") or ""
            if login != ME or login.endswith(BOTS): continue
            body = c.get("body") or ""
            state = c.get("state")
            human = (bool(body.strip()) or state in ("APPROVED", "CHANGES_REQUESTED")) and not AUTO.search(body)
            if human and c.get(tkey):
                ev.append((c[tkey], login, body[:120]))
    return f"{repo}#{n}", sorted(ev)
jobs = [(repo, p["number"]) for repo, r in d["repos"].items() for p in r["prs"] if p["state"] == "open"]
with ThreadPoolExecutor(8) as ex:
    res = dict(ex.map(lambda a: one(*a), jobs))
json.dump(res, open("data/2026-W43_human_reviews.json", "w"), indent=1)
print(len(res), sum(bool(v) for v in res.values()))
