import json, re, subprocess, sys
from concurrent.futures import ThreadPoolExecutor
CLAUDE = re.compile(r"Written by Claude Code|Generated by \[?Claude Code|nightly-code-review|Nightly (code[- ])?review|<!-- (rustacean|analysis)-review|^/rustacean-review|^Replies to the /analysis-review|^Hand review|^Code review|^Review of the whole PR", re.I | re.M)
def gh(path):
    out = subprocess.run(["gh", "api", path, "--paginate"], capture_output=True, text=True, env={"GH_PAGER": "cat", **__import__("os").environ})
    txt = out.stdout.replace("][", ",")
    return json.loads(txt or "[]")
def facts(repo, p):
    n = p["number"]
    revs = gh(f"repos/{repo}/pulls/{n}/reviews?per_page=100")
    inl = gh(f"repos/{repo}/pulls/{n}/comments?per_page=100")
    iss = gh(f"repos/{repo}/issues/{n}/comments?per_page=100")
    times = []
    claude_review_ids = set()
    for r in revs:
        if r["user"]["login"] != "olgabot": continue
        b = r.get("body") or ""
        if CLAUDE.search(b): claude_review_ids.add(r["id"]); continue
        if b.strip() or r["state"] in ("APPROVED", "CHANGES_REQUESTED"):
            times.append(r["submitted_at"])
    for c in inl:
        if c["user"]["login"] != "olgabot": continue
        if CLAUDE.search(c.get("body") or ""): continue
        times.append(c["created_at"])
    for c in iss:
        if c["user"]["login"] != "olgabot": continue
        if CLAUDE.search(c.get("body") or ""): continue
        times.append(c["created_at"])
    last = max(times) if times else None
    lc = p.get("last_commit_at")
    return n, {"n_human": len(times), "last_human": last, "commits_after": bool(last and lc and lc > last)}
d = json.load(open("prs.json"))
res = {}
for repo, r in d["repos"].items():
    with ThreadPoolExecutor(8) as ex:
        res[repo] = dict(ex.map(lambda p: facts(repo, p), [p for p in r["prs"] if p["state"] == "open"]))
json.dump(res, open("human.json", "w"), indent=1)
for repo, x in res.items():
    print(repo, sum(1 for v in x.values() if v["n_human"]), "of", len(x), "have a human review")
    print({k: v for k, v in x.items() if v["n_human"]})
