"""Write the Sherlock job that runs kmerseek for stages C, D and E. kmerseek is not modified.

For every dataset, setting (alphabet, k, mask) and scaled value (1 = no sketch
subsampling, 10 = the subsampled setting), the job builds one index of that dataset's
references and runs two searches of its queries:

  candidates.csv.gz  candidate generation alone: every target sharing one retained k-mer,
                     no score filter (config kmerseek.candidate_flags). Stages C (scaled 1)
                     and D (scaled 10) take the candidate *set* from here and rescore it.
  e2e.csv.gz         the dataset's existing pipeline flags and extension (stage E).

Every command runs under /usr/bin/time -v, so wall time and peak memory are recorded per
step. The effective parameters of every index and search go to params.tsv. The fixtures
run the same way, one fixture set per setting.

kmerseek index and search never run on the laptop (a hook refuses them); this file only
writes the scripts.
"""

from __future__ import annotations

import shlex
from pathlib import Path

import fixtures
from panels import write_fasta

RUN_SH = r"""#!/usr/bin/env bash
# Generated by scripts/stage_diagnostic/kmerseek_job.py. One kmerseek step per line of
# steps.tsv: index, candidate search, end-to-end search. Failures are recorded, not fatal.
set -uo pipefail
cd "$(dirname "$0")"
SIF={sif}
KS="apptainer exec --bind /scratch $SIF kmerseek"
apptainer exec $SIF cat /etc/kmerseek_git_sha > kmerseek_git_sha.txt 2>/dev/null || echo unknown > kmerseek_git_sha.txt
printf 'step\tdataset\tsetting\tscaled\texit\tcommand\n' > params.tsv
run() {{  # run <step> <dataset> <setting> <scaled> <outdir> <args...>
  local step=$1 ds=$2 st=$3 sc=$4 out=$5; shift 5
  mkdir -p "$out"
  /usr/bin/time -v -o "$out/$step.time" $KS "$@" > "$out/$step.stdout" 2> "$out/$step.stderr"
  local rc=$?
  printf '%s\t%s\t%s\t%s\t%s\t%s\n' "$step" "$ds" "$st" "$sc" "$rc" "kmerseek $*" >> params.tsv
  return $rc
}}
"""


def setting_label(s: dict) -> str:
    return f"{s['alphabet']}.k{s['ksize']}" + (".mask" if s["mask"] else "")


def write_job(cfg: dict, data_dir: Path, job_dir: Path, datasets: list[str]) -> Path:
    ks = cfg["kmerseek"]
    job_dir.mkdir(parents=True, exist_ok=True)
    lines = [RUN_SH.format(sif=ks["sif"])]
    scaled_values = [ks["scaled_no_subsampling"], ks["scaled_sketch"]]
    fixture_settings = {}
    for ds in datasets:
        e2e = ks["end_to_end"]["ice_binding" if ds == "ice_binding" else "toxin"]
        for s in ks["settings"][ds]:
            lab = setting_label(s)
            fixture_settings[lab] = s
            for sc in scaled_values:
                out = f"out/{ds}/{lab}/s{sc}"
                idx = f"{out}/idx"
                index_args = [
                    "index", "--input", f"data/{ds}/references.fasta", "--output", idx,
                    "--alphabet", s["alphabet"], "--ksize", str(s["ksize"]), "--scaled", str(sc),
                ]  # fmt: skip
                if s["mask"]:
                    index_args.append("--remove-low-complexity")
                extend = e2e["extend"] and s["penalty"] is not None
                if extend:
                    index_args += [
                        "--extend-mismatch-penalty", str(s["penalty"]),
                        "--extend-xdrop", str(s["xdrop"]),
                        "--ka-survival-out", f"{out}/ka_survival.csv",
                    ]  # fmt: skip
                else:
                    index_args += ["--ka-queries", "0"]
                search = [
                    "search", "--query", f"data/{ds}/queries.fasta", "--target", idx,
                    "--alphabet", s["alphabet"], "--ksize", str(s["ksize"]),
                ]  # fmt: skip
                cand = (
                    search
                    + shlex.split(ks["candidate_flags"])
                    + ["--output", f"{out}/candidates.csv"]
                )
                e2e_args = search + shlex.split(e2e["flags"]) + ["--output", f"{out}/e2e.csv"]
                if extend:
                    e2e_args += [
                        "--extend-mismatch-penalty", str(s["penalty"]),
                        "--extend-xdrop", str(s["xdrop"]), "--ka-queries", "0",
                    ]  # fmt: skip
                lines.append(f"\n# {ds} {lab} scaled {sc}")
                lines.append(_run("index", ds, lab, sc, out, index_args))
                lines.append(_run("candidates", ds, lab, sc, out, cand))
                lines.append(_run("e2e", ds, lab, sc, out, e2e_args))
                if extend:
                    # no stored fit -> the pipeline would record "nofit"; rank this setting by
                    # Poisson score from the same flags without extension instead, labelled
                    e2e_plain = (
                        search + shlex.split(e2e["flags"]) + ["--output", f"{out}/e2e_noextend.csv"]
                    )
                    lines.append(
                        f'grep -q "no Karlin-Altschul fit" {out}/e2e.stderr && '
                        + _run("e2e_noextend", ds, lab, sc, out, e2e_plain)
                    )
                lines.append(f"gzip -f {out}/*.csv 2>/dev/null; rm -rf {idx}")
    # fixtures: one set per setting, scaled 1 and 10, candidate flags only
    for lab, s in sorted(fixture_settings.items()):
        q, r = fixtures.build(s["alphabet"], s["ksize"], ks["scaled_sketch"], s["mask"])
        d = job_dir / "data" / f"fixtures_{lab}"
        d.mkdir(parents=True, exist_ok=True)
        write_fasta(d / "queries.fasta", sorted(q.items()))
        write_fasta(d / "references.fasta", sorted(r.items()))
        for sc in scaled_values:
            out = f"out/fixtures/{lab}/s{sc}"
            idx = f"{out}/idx"
            ia = [
                "index", "--input", f"data/fixtures_{lab}/references.fasta", "--output", idx,
                "--alphabet", s["alphabet"], "--ksize", str(s["ksize"]), "--scaled", str(sc),
                "--ka-queries", "0",
            ]  # fmt: skip
            if s["mask"]:
                ia.append("--remove-low-complexity")
            sa = [
                "search", "--query", f"data/fixtures_{lab}/queries.fasta", "--target", idx,
                "--alphabet", s["alphabet"], "--ksize", str(s["ksize"]),
            ] + shlex.split(ks["candidate_flags"]) + ["--output", f"{out}/candidates.csv"]  # fmt: skip
            lines.append(f"\n# fixtures {lab} scaled {sc}")
            lines.append(_run("index", "fixtures", lab, sc, out, ia))
            lines.append(_run("candidates", "fixtures", lab, sc, out, sa))
            lines.append(f"gzip -f {out}/*.csv 2>/dev/null; rm -rf {idx}")
    lines.append("\necho done > DONE\n")
    run_sh = job_dir / "run.sh"
    run_sh.write_text("\n".join(lines))
    run_sh.chmod(0o755)
    (job_dir / "submit.sbatch").write_text(
        "#!/usr/bin/env bash\n"
        "#SBATCH --job-name=nb350-stage-diag\n"
        "#SBATCH --account=ayeletv\n"
        "#SBATCH --partition=hns,normal\n"
        "#SBATCH --cpus-per-task=4\n"
        "#SBATCH --mem=16G\n"
        "#SBATCH --time=01:00:00\n"
        "#SBATCH --output=slurm-%j.out\n"
        'cd "$SLURM_SUBMIT_DIR"\n'
        "bash run.sh\n"
    )
    return job_dir


def _run(step, ds, lab, sc, out, args) -> str:
    return f"run {step} {ds} {lab} {sc} {out} " + " ".join(shlex.quote(a) for a in args)
